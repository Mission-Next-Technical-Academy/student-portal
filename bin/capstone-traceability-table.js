#!/usr/bin/env node
'use strict';
// Prints the capstone traceability table (markdown) from
// portal/soc-capstone-traceability.js. Paste the output under
// "Traceability table" in docs/workstreams/CAPSTONE_SKILL_BACKFILL.md:
//   node bin/capstone-traceability-table.js
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(root, 'portal/soc-capstone-traceability.js'), 'utf8'), context);
const data = JSON.parse(JSON.stringify(vm.runInContext('SocCapstoneTraceability', context)));

const cell = (text) => String(text).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const M12_SHARED = new Set(['portal/soc-m12-assessment-console.js#mount', 'portal/soc-m12-tool-bridge.js', 'portal/soc-m12-assessment-state.js']);
const short = (ref) => ref.replace(/^portal\//, '').replace(/^soc-console-tools\.js#PACKS\./, 'tools PACKS.');

const practice = (entry) => {
  if (!entry.practice.length) return entry.exposedIn ? `none (tool open in ${entry.exposedIn.map((x) => `${x.module} ${x.tab}`).join(', ')})` : 'none';
  return entry.practice.map((p) => `${p.module} ${p.where.tab} / ${p.where.step}${p.coverage === 'generic' ? ' (generic)' : ''}`).join('<br>');
};
const prove = (entry) => (entry.prove.length ? entry.prove.map((v) => `${v.module} ${v.criterion}`).join('<br>') : 'none');
const code = (entry) => entry.code.filter((ref) => !M12_SHARED.has(ref)).map(short).join('<br>');

const lines = [
  `Generated by \`node bin/capstone-traceability-table.js\` from \`portal/soc-capstone-traceability.js\` (${data.entries.length} mechanics). `
  + 'Practice = guided-lab step (M03 step id, otherwise step title); "(generic)" means a ticket-driven step that only touches the mechanic. '
  + 'Prove = rubric criterion id in that module (M01/M02: score-breakdown key). '
  + `Every row also runs through the M12 console (\`soc-m12-assessment-console.js\` mount(), which embeds PACKS ${data.embeddedPacks.join(', ')}), \`soc-m12-tool-bridge.js\` and \`soc-m12-assessment-state.js\`; those three files are left out of the code column.`,
  '',
  '| M12 mechanic | M12 criterion | M12 tab | Practice It (guided) | Prove It | Shared code | Gap |',
  '| --- | --- | --- | --- | --- | --- | --- |',
];
for (const entry of data.entries) {
  lines.push(`| \`${entry.id}\`: ${cell(entry.capstone.mechanic)} | ${entry.capstone.criterion} | ${entry.capstone.tab} | ${cell(practice(entry))} | ${cell(prove(entry))} | ${cell(code(entry))} | ${cell(entry.gap || '')} |`);
}
const gaps = data.entries.filter((e) => !e.practice.length || !e.prove.length);
lines.push('', `${gaps.length} of ${data.entries.length} mechanics still have a gap: ${gaps.map((e) => `\`${e.id}\``).join(', ')}.`);
console.log(lines.join('\n'));
