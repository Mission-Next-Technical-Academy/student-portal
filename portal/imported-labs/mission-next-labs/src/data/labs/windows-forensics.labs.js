  function buildTimelineRows() {
    const rows = [];
    const baseMinute = 8 * 60;
    for (let i = 0; i < 400; i += 1) {
      const minute = baseMinute + i;
      const hh = String(Math.floor(minute / 60)).padStart(2, '0');
      const mm = String(minute % 60).padStart(2, '0');
      const fullPath =
        i < 310 ? `C:\\Users\\jdoe\\Documents\\Quarterly\\report-${String(i).padStart(3, '0')}.docx`
        : i < 360 ? `C:\\Users\\jdoe\\AppData\\Local\\Temp\\export\\acct-${String(i - 309).padStart(3, '0')}.csv`
        : i < 390 ? `E:\\staging\\acct-${String(i - 309).padStart(3, '0')}.csv`
        : `C:\\Users\\jdoe\\AppData\\Local\\Temp\\export\\finance-bundle-${i - 389}.zip`;
      rows.push({
        id: `wf3-${i}`,
        FullPath: fullPath,
        Created0x10: `2026-04-12 ${hh}:${mm}:14`,
        Modified0x10: `2026-04-12 ${hh}:${mm}:41`,
        EntryNumber: String(1000 + i),
        Size: i < 390 ? `${24 + (i % 9)} KB` : `${4 + (i % 3)} MB`,
        ZoneId: i >= 360 ? '3' : '0',
        LogFileSeq: `0x${(20000 + i).toString(16)}`,
      });
    }
    return rows;
  }

